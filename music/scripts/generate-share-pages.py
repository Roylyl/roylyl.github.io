#!/usr/bin/env python3
"""Generate song-specific share metadata without copying media into the site."""

import html
import json
import os
from pathlib import Path
from string import Template
from urllib.parse import quote

MUSIC_SITE = Path(__file__).resolve().parents[1]
MUSIC_SOURCE = Path(os.environ.get("ROYLYL_MUSIC_REPO", MUSIC_SITE.parents[1] / "Music"))
PUBLIC_ROOT = "https://roylyl.github.io/music/"
RESOURCE_VERSION = "20261105-web-97"
TEMPLATE = Template((Path(__file__).parent / "share-template.html").read_text(encoding="utf-8"))


def share_cover(track):
    """Use an existing JPEG/PNG original instead of the player's WebP derivative."""
    web_cover = Path(track["cover"])
    for extension in (".jpg", ".jpeg", ".png"):
        original = web_cover.with_suffix(extension)
        if (MUSIC_SOURCE / original).is_file():
            return original
    if not (MUSIC_SOURCE / web_cover).is_file():
        raise FileNotFoundError(MUSIC_SOURCE / web_cover)
    return web_cover


def page(track, image_path):
    song_id = quote(track["id"], safe="")
    escape = lambda value: html.escape(str(value), quote=True)
    image = "https://raw.githubusercontent.com/Roylyl/Music/main/" + quote(image_path.as_posix(), safe="/")
    return TEMPLATE.substitute(
        title=escape(f'{track["title"]}－{track["artist"]}'),
        name=escape(track["title"]), artist=escape(track["artist"]), album=escape(track["album"]),
        description=escape(f'{track["artist"]}｜{track["album"]}｜Roylyl Music'),
        canonical=PUBLIC_ROOT + "share/" + song_id + ".html", image=image,
        image_type={".webp": "image/webp", ".png": "image/png"}.get(image_path.suffix.lower(), "image/jpeg"),
        listen="../?track=" + song_id + "&amp;full=1&amp;autoplay=1", resource_version=RESOURCE_VERSION,
    )


def main():
    catalog_path = MUSIC_SOURCE / "catalog.json"
    if not catalog_path.is_file():
        catalog_path = MUSIC_SITE / "data/catalog.json"
    tracks = json.loads(catalog_path.read_text(encoding="utf-8"))["tracks"]
    share_dir = MUSIC_SITE / "share"
    share_dir.mkdir(exist_ok=True)
    covers = {}
    for track in tracks:
        if track["cover"] not in covers:
            covers[track["cover"]] = share_cover(track)
        destination = share_dir / f'{track["id"]}.html'
        destination.write_text(page(track, covers[track["cover"]]), encoding="utf-8")
    write_share_index(tracks)
    originals = sum(cover.suffix.lower() in (".jpg", ".jpeg", ".png") for cover in covers.values())
    print(f"已生成{len(tracks)}个歌曲分享页；{originals}/{len(covers)}张专辑封面使用云端JPEG/PNG原图，网站未复制封面")


def write_share_index(tracks):
    ids = json.dumps([track["id"] for track in tracks], ensure_ascii=False, separators=(",", ":"))
    (MUSIC_SITE / "share-pages.js").write_text(
        "// Generated by scripts/generate-share-pages.py; metadata pages available at publication.\n"
        + "window.RoylylMusicShareIds=new Set(" + ids + ");\n", encoding="utf-8")


if __name__ == "__main__":
    main()
